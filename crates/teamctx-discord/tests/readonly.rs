//! Read-only guard (plan sections 7.3 and 13, ADR 0005): no product source in the
//! workspace may write to Discord, except replies to interactions.
//!
//! The test lexes every `.rs` file under `crates/*/src`, `crates/*/examples`,
//! `crates/*/benches`, `crates/*/build.rs` and `xtask/src`. Comments are dropped and
//! string literals are kept apart from code, so a name in a doc comment or a log message
//! is not a hit, while a Discord route inside a URL string still is. Integration tests
//! are not scanned: they never ship, and the sync fakes in them model Discord-side
//! deletes. The rules, each with its own self-test below:
//!
//! - **R1** A call or path to a `twilight-http` write method (`.create_message(`,
//!   `Client::delete_message`, ...). Free functions with the same name, such as the
//!   store's local `delete_message`, are not calls into Discord and are not flagged.
//! - **R2** Any mention of a `twilight-http` write request builder or route
//!   (`CreateMessage`, `Route::CreateReaction`, ...).
//! - **R3** In a file that names `twilight_http`: every write-shaped method or type
//!   (`create_*`, `update_*`, `delete_*`, `add_*`, `remove_*`, `set_*`, ... and the
//!   CamelCase forms) must be on [`ALLOWED_METHODS`] / [`ALLOWED_TYPES`]. This catches
//!   write methods newer than the R1/R2 lists.
//! - **R4** A file that holds a Discord REST route in a string literal must not use an
//!   HTTP write method (`POST`, `PUT`, `PATCH`, `DELETE`, `.post(` ...) unless every
//!   Discord route in it is an interaction route ([`allowed_route`]).
//!
//! The allow-list is the interaction surface of plan section 7.3 and nothing else:
//! answering an interaction (`create_response`, `POST /interactions/{id}/{token}/callback`),
//! editing that answer after a defer (`update_response`,
//! `PATCH /webhooks/{app}/{token}/messages/@original`) and registering the slash commands
//! on start (`set_guild_commands`, `set_global_commands`, `PUT .../commands`). Widening
//! it needs a maintainer-approved change to ADR 0005.
//!
//! Not covered (documented in `docs/testing/guards.md`): routes assembled from pieces in
//! different string literals, HTTP methods passed in from another file, and code
//! generated by macros from other crates. Review still matters; this guard makes the
//! common ways of writing a write call fail CI.

