// ---------------------------------------------------------------------------------------
// Lexer: just enough Rust to tell code, comments and string literals apart.
// ---------------------------------------------------------------------------------------

#[derive(Debug, Clone, PartialEq, Eq)]
enum Tok {
    Ident(String),
    Punct(char),
    /// The text between the quotes of a string, byte string or raw string literal.
    Str(String),
}

#[derive(Debug, Clone)]
struct Token {
    tok: Tok,
    line: usize,
}

fn is_ident_start(c: char) -> bool {
    c == '_' || c.is_alphabetic()
}

fn is_ident_continue(c: char) -> bool {
    c == '_' || c.is_alphanumeric()
}

struct Lexer {
    chars: Vec<char>,
    pos: usize,
    line: usize,
    out: Vec<Token>,
}

impl Lexer {
    fn at(&self, offset: usize) -> Option<char> {
        self.chars.get(self.pos + offset).copied()
    }

    fn bump(&mut self) -> Option<char> {
        let c = self.at(0)?;
        self.pos += 1;
        if c == '\n' {
            self.line += 1;
        }
        Some(c)
    }

    fn push(&mut self, tok: Tok, line: usize) {
        self.out.push(Token { tok, line });
    }

    fn run(mut self) -> Vec<Token> {
        while let Some(c) = self.at(0) {
            let line = self.line;
            match c {
                '/' if self.at(1) == Some('/') => {
                    while self.at(0).is_some_and(|c| c != '\n') {
                        self.bump();
                    }
                }
                '/' if self.at(1) == Some('*') => self.block_comment(),
                '"' => {
                    self.bump();
                    let text = self.quoted();
                    self.push(Tok::Str(text), line);
                }
                '\'' => self.quote_or_lifetime(),
                'b' | 'c' | 'r' if self.literal_prefix().is_some() => {
                    let (skip, raw) = self.literal_prefix().unwrap_or((0, false));
                    for _ in 0..skip {
                        self.bump();
                    }
                    if raw {
                        let text = self.raw();
                        self.push(Tok::Str(text), line);
                    } else if self.at(0) == Some('\'') {
                        self.quote_or_lifetime();
                    } else {
                        self.bump();
                        let text = self.quoted();
                        self.push(Tok::Str(text), line);
                    }
                }
                'r' if self.at(1) == Some('#') && self.at(2).is_some_and(is_ident_start) => {
                    // A raw identifier such as `r#type`.
                    self.bump();
                    self.bump();
                    self.ident(line);
                }
                c if is_ident_start(c) => self.ident(line),
                c if c.is_ascii_digit() => {
                    while self.at(0).is_some_and(is_ident_continue) {
                        self.bump();
                    }
                }
                c if c.is_whitespace() => {
                    self.bump();
                }
                c => {
                    self.bump();
                    self.push(Tok::Punct(c), line);
                }
            }
        }
        self.out
    }

    /// For `b"`, `b'`, `c"`, `r"`, `r#"`, `br"`, `br#"`, `cr"`, `cr#"`: how many prefix
    /// characters to skip and whether the literal is raw. `None` for an identifier.
    fn literal_prefix(&self) -> Option<(usize, bool)> {
        let first = self.at(0)?;
        let (skip, raw) = match (first, self.at(1)) {
            ('b' | 'c', Some('r')) => (2, true),
            ('r', _) => (1, true),
            ('b', Some('"' | '\'')) | ('c', Some('"')) => return Some((1, false)),
            _ => return None,
        };
        let mut offset = skip;
        while self.at(offset) == Some('#') {
            offset += 1;
        }
        (self.at(offset) == Some('"')).then_some((skip, raw))
    }

    fn ident(&mut self, line: usize) {
        let mut name = String::new();
        while let Some(c) = self.at(0).filter(|c| is_ident_continue(*c)) {
            name.push(c);
            self.bump();
        }
        self.push(Tok::Ident(name), line);
    }

    fn block_comment(&mut self) {
        let mut depth = 0_usize;
        while let Some(c) = self.at(0) {
            if c == '/' && self.at(1) == Some('*') {
                depth += 1;
                self.bump();
            } else if c == '*' && self.at(1) == Some('/') {
                depth -= 1;
                self.bump();
                if depth == 0 {
                    self.bump();
                    return;
                }
            }
            self.bump();
        }
    }

    /// The body of a `"..."` literal; the opening quote is already consumed.
    fn quoted(&mut self) -> String {
        let mut text = String::new();
        while let Some(c) = self.bump() {
            match c {
                '"' => break,
                '\\' => {
                    text.push(c);
                    if let Some(next) = self.bump() {
                        text.push(next);
                    }
                }
                c => text.push(c),
            }
        }
        text
    }

    /// The body of `#*"..."#*`; the `r`/`br`/`cr` prefix is already consumed.
    fn raw(&mut self) -> String {
        let mut hashes = 0;
        while self.at(0) == Some('#') {
            hashes += 1;
            self.bump();
        }
        self.bump(); // the opening quote
        let mut text = String::new();
        while let Some(c) = self.bump() {
            if c == '"' && (0..hashes).all(|i| self.at(i) == Some('#')) {
                for _ in 0..hashes {
                    self.bump();
                }
                break;
            }
            text.push(c);
        }
        text
    }

    /// A char literal (`'x'`, `'\''`, `'"'`) is skipped; a lifetime or label (`'a`) only
    /// loses its quote, and the name after it is lexed as an identifier.
    fn quote_or_lifetime(&mut self) {
        self.bump();
        if self.at(0) == Some('\\') {
            self.bump();
            self.bump();
            while self.at(0).is_some_and(|c| c != '\'') {
                self.bump();
            }
            self.bump();
        } else if self.at(1) == Some('\'') {
            self.bump();
            self.bump();
        }
    }
}

fn lex(source: &str) -> Vec<Token> {
    Lexer {
        chars: source.chars().collect(),
        pos: 0,
        line: 1,
        out: Vec::new(),
    }
    .run()
}

// ---------------------------------------------------------------------------------------
// Rules
// ---------------------------------------------------------------------------------------

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Rule {
    /// R1.
    WriteMethod,
    /// R2.
    WriteType,
    /// R3.
    UnreviewedWrite,
    /// R4.
    RestWrite,
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct Violation {
    file: String,
    line: usize,
    rule: Rule,
    what: String,
}

impl fmt::Display for Violation {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let why = match self.rule {
            Rule::WriteMethod => "R1 twilight-http write method",
            Rule::WriteType => "R2 twilight-http write request or route",
            Rule::UnreviewedWrite => "R3 write-shaped twilight-http name not on the allow-list",
            Rule::RestWrite => "R4 HTTP write method in a file with a Discord REST route",
        };
        write!(f, "{}:{}: {why}: {}", self.file, self.line, self.what)
    }
}

fn ident(token: Option<&Token>) -> Option<&str> {
    match token.map(|t| &t.tok) {
        Some(Tok::Ident(name)) => Some(name),
        _ => None,
    }
}

fn punct(token: Option<&Token>, c: char) -> bool {
    matches!(token.map(|t| &t.tok), Some(Tok::Punct(p)) if *p == c)
}

/// Whether the identifier at `i` is called as a method (`.name`) or named through a
/// path (`Type::name`, `use a::name`).
fn in_call_or_path(tokens: &[Token], i: usize) -> bool {
    i >= 1
        && (punct(tokens.get(i - 1), '.')
            || (i >= 2 && punct(tokens.get(i - 1), ':') && punct(tokens.get(i - 2), ':')))
}

/// `create_message` and `CreateMessage` both start with the word `create`.
fn write_shaped(name: &str) -> bool {
    let lower = name.to_ascii_lowercase();
    WRITE_PREFIXES.iter().any(|prefix| {
        lower.starts_with(prefix)
            && name[prefix.len()..]
                .chars()
                .next()
                .is_some_and(|next| next == '_' || next.is_ascii_uppercase())
    })
}

/// Whether a string literal names a Discord REST route. Web links such as
/// `https://discord.com/channels/...` (jump links) and the OAuth2 invite page are not
/// REST routes.
fn discord_route(literal: &str) -> bool {
    let text = literal.to_ascii_lowercase();
    if text.contains("discord.com/api") || text.contains("discordapp.com/api") {
        return true;
    }
    if text.contains("discord.com")
        || text.contains("discordapp.com")
        || text.contains("discord.gg")
    {
        return false;
    }
    ROUTE_ROOTS
        .iter()
        .any(|root| text.starts_with(root) || text.contains(&format!("/{root}")))
}

/// The interaction routes of plan section 7.3.
fn allowed_route(literal: &str) -> bool {
    let text = literal.to_ascii_lowercase();
    let path = text
        .split(['?', '#'])
        .next()
        .unwrap_or("")
        .trim_end_matches('/');
    (path.contains("interactions/") && path.ends_with("/callback"))
        || (path.contains("webhooks/") && path.ends_with("/messages/@original"))
        || (path.contains("applications/") && path.ends_with("/commands"))
}

fn http_write_marker(tokens: &[Token], i: usize) -> Option<String> {
    match &tokens[i].tok {
        Tok::Ident(name) if WRITE_HTTP_METHODS.contains(&name.as_str()) => Some(name.clone()),
        Tok::Ident(name)
            if punct(tokens.get(i.wrapping_sub(1)), '.')
                && WRITE_HTTP_METHODS
                    .iter()
                    .any(|m| m.eq_ignore_ascii_case(name) && name.as_str() != *m) =>
        {
            Some(format!(".{name}("))
        }
        Tok::Str(text) if WRITE_HTTP_METHODS.contains(&text.as_str()) => Some(format!("{text:?}")),
        _ => None,
    }
}

fn scan(file: &str, source: &str) -> Vec<Violation> {
    let tokens = lex(source);
    let mut found = Vec::new();
    let mut flag = |line, rule, what: String| {
        found.push(Violation {
            file: file.to_owned(),
            line,
            rule,
            what,
        });
    };
    let uses_twilight_http = tokens
        .iter()
        .any(|t| matches!(&t.tok, Tok::Ident(name) if name == "twilight_http"));

    for (i, token) in tokens.iter().enumerate() {
        let Some(name) = ident(Some(token)) else {
            continue;
        };
        if DENIED_METHODS.contains(&name) && in_call_or_path(&tokens, i) {
            flag(token.line, Rule::WriteMethod, name.to_owned());
        } else if DENIED_TYPES.contains(&name) {
            flag(token.line, Rule::WriteType, name.to_owned());
        } else if uses_twilight_http && write_shaped(name) {
            let camel = name.starts_with(|c: char| c.is_ascii_uppercase());
            let unreviewed = if camel {
                !ALLOWED_TYPES.contains(&name)
            } else {
                in_call_or_path(&tokens, i) && !ALLOWED_METHODS.contains(&name)
            };
            if unreviewed {
                flag(token.line, Rule::UnreviewedWrite, name.to_owned());
            }
        }
    }

    // R4: a Discord route that is not an interaction route, plus any write method.
    let routes: Vec<&Token> = tokens
        .iter()
        .filter(|t| matches!(&t.tok, Tok::Str(text) if discord_route(text)))
        .collect();
    let unlisted = routes
        .iter()
        .find(|t| matches!(&t.tok, Tok::Str(text) if !allowed_route(text)));
    if let Some(route) = unlisted {
        for i in 0..tokens.len() {
            if let Some(marker) = http_write_marker(&tokens, i) {
                let Tok::Str(text) = &route.tok else {
                    continue;
                };
                flag(
                    tokens[i].line,
                    Rule::RestWrite,
                    format!("{marker} with route {text:?} (line {})", route.line),
                );
            }
        }
    }
    found
}

