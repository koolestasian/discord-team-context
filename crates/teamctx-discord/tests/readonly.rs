fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .expect("workspace root")
}

fn rust_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries {
        let path = entry.expect("directory entry").path();
        if path.is_dir() {
            rust_files(&path, out);
        } else if path.extension().is_some_and(|ext| ext == "rs") {
            out.push(path);
        }
    }
}

/// Every product source file: `crates/*/{src,examples,benches,build.rs}` and `xtask/src`.
fn product_sources(root: &Path) -> Vec<PathBuf> {
    let mut files = Vec::new();
    let crates = fs::read_dir(root.join("crates")).expect("crates directory");
    for krate in crates {
        let krate = krate.expect("crate entry").path();
        for dir in ["src", "examples", "benches"] {
            rust_files(&krate.join(dir), &mut files);
        }
        let build = krate.join("build.rs");
        if build.is_file() {
            files.push(build);
        }
    }
    rust_files(&root.join("xtask/src"), &mut files);
    files.sort();
    files
}

