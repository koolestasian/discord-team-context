#[test]
fn product_code_has_no_discord_write_calls() {
    let root = workspace_root();
    let files = product_sources(&root);
    let names: Vec<String> = files
        .iter()
        .map(|path| {
            path.strip_prefix(&root)
                .expect("inside the workspace")
                .to_string_lossy()
                .replace('\\', "/")
        })
        .collect();
    // The walk found the real tree, so an empty pass cannot hide a broken path.
    for expected in [
        "crates/teamctx-discord/src/sync/rest.rs",
        "crates/teamctx-discord/src/lib.rs",
        "crates/teamctx-llm/src/http.rs",
        "crates/teamctx-server/src/lib.rs",
        "crates/teamctx/src/main.rs",
        "xtask/src/main.rs",
    ] {
        assert!(
            names.iter().any(|n| n == expected),
            "{expected} not scanned"
        );
    }
    assert!(files.len() >= 50, "only {} files scanned", files.len());

    let mut violations = Vec::new();
    for (path, name) in files.iter().zip(&names) {
        let source = fs::read_to_string(path).expect("read source");
        violations.extend(scan(name, &source));
    }
    let report: Vec<String> = violations.iter().map(ToString::to_string).collect();
    assert!(
        report.is_empty(),
        "Discord write calls outside interaction replies (ADR 0005, docs/testing/guards.md):\n{}",
        report.join("\n")
    );
}

